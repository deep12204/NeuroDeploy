def find_free_port(start_port=8010, max_port=8999):
    for port in range(start_port, max_port):
        with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as s:
            try:
                s.bind(('127.0.0.1', port))
                return port
            except OSError:
                continue
    return 8080

def inspect_env_vars(repo_path: str, file_list: list):
    env_keys = {}

    # Check .env.example / .env.sample / .env
    for fname in ['.env.example', '.env.sample', '.env.local.example', '.env']:
        for rel in file_list:
            if os.path.basename(rel).lower() == fname:
                full_path = os.path.join(repo_path, rel)
                try:
                    with open(full_path, 'r', encoding='utf-8', errors='ignore') as f:
                        for line in f:
                            line = line.strip()
                            if line and not line.startswith('#') and '=' in line:
                                k, v = line.split('=', 1)
                                env_keys[k.strip()] = v.strip().strip("'\"")
                except Exception:
                    pass

    py_env_regex = re.compile(r"""(?:os\.environ\.get|os\.getenv)\s*\(\s*['"]([A-Za-z0-9_]+)['"](?:\s*,\s*['"](.*?)['"])?\s*\)""")
    js_env_regex = re.compile(r"""(?:process\.env\.([A-Za-z0-9_]+)|process\.env\[['"]([A-Za-z0-9_]+)['"]\])""")

    for rel in file_list[:80]:
        ext = os.path.splitext(rel)[1].lower()
        if ext in ['.py', '.js', '.ts', '.jsx', '.tsx']:
            full_path = os.path.join(repo_path, rel)
            try:
                content = open(full_path, 'r', encoding='utf-8', errors='ignore').read(30000)
                if ext == '.py':
                    for match in py_env_regex.finditer(content):
                        k = match.group(1)
                        default_val = match.group(2) or ""
                        if k not in env_keys and not k.startswith(('PATH', 'PYTHON', 'TERM')):
                            env_keys[k] = default_val
                else:
                    for match in js_env_regex.finditer(content):
                        k = match.group(1) or match.group(2)
                        if k and k not in env_keys and not k.startswith(('NODE_ENV', 'PATH')):
                            env_keys[k] = ""
            except Exception:
                pass

    return [
        {"key": k, "default_value": v, "required": not bool(v)}
        for k, v in env_keys.items()
    ]


def launch_app(repo_id: str, env_vars: dict = None, custom_command: str = None):
    store = load_store(repo_id)
    if not store:
        raise ValueError("Repository metadata not found. Please index the repository first.")

    repo_path = os.path.abspath(store["repo_path"])
    file_list = store.get("file_list", [])
    tech_stack = store.get("tech_stack", [])
    stack_names = [t['name'].lower() if isinstance(t, dict) else str(t).lower() for t in tech_stack]

    port = find_free_port()
    deploy_id = f"deploy_{repo_id}_{int(time.time())}"
    log_file_path = os.path.abspath(os.path.join(LOGS_DIR, f"{deploy_id}.log"))

    if custom_command and custom_command.strip():
        cmd = custom_command.strip()
    else:
        py_files = [f for f in file_list if f.endswith('.py')]
        if 'fastapi' in stack_names or any('main.py' in f for f in py_files):
            # Check if backend directory exists
            if os.path.exists(os.path.join(repo_path, 'backend', 'main.py')):
                cmd = f'"{sys.executable}" -m uvicorn backend.main:app --host 0.0.0.0 --port {port}'
            elif os.path.exists(os.path.join(repo_path, 'main.py')):
                cmd = f'"{sys.executable}" -m uvicorn main:app --host 0.0.0.0 --port {port}'
            elif os.path.exists(os.path.join(repo_path, 'app.py')):
                cmd = f'"{sys.executable}" app.py'
            else:
                cmd = f'"{sys.executable}" {py_files[0]}'
        elif 'node.js' in stack_names or any(f == 'package.json' for f in file_list):
            cmd = f'npm start -- --port {port}'
        else:
            cmd = f'"{sys.executable}" -m http.server {port}'

    run_env = os.environ.copy()
    run_env["PORT"] = str(port)
    run_env["HOST"] = "0.0.0.0"
    if env_vars:
        for k, v in env_vars.items():
            run_env[str(k)] = str(v)

    log_file = open(log_file_path, "w", encoding="utf-8")
    log_file.write(f"=== NeuroDeploy Sandbox Launched at {time.strftime('%Y-%m-%d %H:%M:%S')} ===\n")
    log_file.write(f"Command: {cmd}\n")
    log_file.write(f"Port: {port}\n")
    log_file.write(f"===========================================================\n\n")
    log_file.flush()

    try:
        proc = subprocess.Popen(
            cmd,
            cwd=repo_path,
            env=run_env,
            stdout=log_file,
            stderr=subprocess.STDOUT,
            shell=True,
            text=True
        )
    except Exception as e:
        log_file.write(f"Launch failed: {str(e)}\n")
        log_file.close()
        raise RuntimeError(f"Failed to start process: {str(e)}")

    deployment_data = {
        "deploy_id": deploy_id,
        "repo_id": repo_id,
        "pid": proc.pid,
        "port": port,
        "url": f"http://localhost:{port}",
        "cmd": cmd,
        "log_file": log_file_path,
        "start_time": time.time(),
        "status": "starting",
        "proc": proc
    }
    ACTIVE_DEPLOYMENTS[deploy_id] = deployment_data

    def probe_health():
        time.sleep(2)
        if proc.poll() is not None:
            deployment_data["status"] = "failed"
            return

        for _ in range(5):
            try:
                res = requests.get(f"http://127.0.0.1:{port}", timeout=1)
                if res.status_code < 500:
                    deployment_data["status"] = "running"
                    return
            except Exception:
                time.sleep(1)

        deployment_data["status"] = "running" if proc.poll() is None else "failed"

    threading.Thread(target=probe_health, daemon=True).start()

    return {
        "deploy_id": deploy_id,
        "status": "running",
        "port": port,
        "url": f"http://localhost:{port}",
        "pid": proc.pid,
        "command": cmd
    }

def stop_app(deploy_id: str):
    if deploy_id not in ACTIVE_DEPLOYMENTS:
        return {"status": "not_found", "message": "Deployment ID not active."}

    data = ACTIVE_DEPLOYMENTS[deploy_id]
    proc = data.get("proc")
    pid = data.get("pid")

    try:
        if pid:
            parent = psutil.Process(pid)
            for child in parent.children(recursive=True):
                child.terminate()
            parent.terminate()
    except Exception:
        pass

    data["status"] = "stopped"
    return {"status": "stopped", "deploy_id": deploy_id}

def get_app_status(deploy_id: str):
    if deploy_id not in ACTIVE_DEPLOYMENTS:
        return {"status": "stopped", "is_running": False}

    data = ACTIVE_DEPLOYMENTS[deploy_id]
    pid = data.get("pid")
    port = data.get("port")
    proc = data.get("proc")

    is_running = False
    cpu_percent = 0.0
    memory_mb = 0.0

    if pid:
        try:
            p = psutil.Process(pid)
            if p.is_running() and p.status() != psutil.STATUS_ZOMBIE:
                is_running = True
                cpu_percent = p.cpu_percent(interval=0.1)
                memory_mb = round(p.memory_info().rss / (1024 * 1024), 2)
        except Exception:
            is_running = False

    uptime_sec = int(time.time() - data.get("start_time", time.time())) if is_running else 0

    return {
        "deploy_id": deploy_id,
        "is_running": is_running,
        "status": "running" if is_running else ("failed" if data.get("status") == "failed" else "stopped"),
        "port": port,
        "url": data.get("url"),
        "pid": pid,
        "uptime_seconds": uptime_sec,
        "cpu_percent": cpu_percent,
        "memory_mb": memory_mb
    }


def get_app_logs(deploy_id: str, tail_lines=100):
    if deploy_id not in ACTIVE_DEPLOYMENTS:
        # Check if log file exists on disk
        log_file_path = os.path.join(LOGS_DIR, f"{deploy_id}.log")
    else:
        log_file_path = ACTIVE_DEPLOYMENTS[deploy_id].get("log_file")

    if not log_file_path or not os.path.exists(log_file_path):
        return {"logs": [], "anomalies_detected": 0}

    try:
        with open(log_file_path, "r", encoding="utf-8", errors="ignore") as f:
            lines = [line.rstrip() for line in f.readlines()][-tail_lines:]

        analyzed = detect_log_anomalies(lines)
        anomaly_count = sum(1 for a in analyzed if a["is_anomaly"])

        return {
            "logs": analyzed,
            "raw_text": "\n".join(lines),
            "anomalies_detected": anomaly_count
        }
    except Exception as e:
        return {"logs": [{"line": f"Error reading logs: {str(e)}", "is_anomaly": True}], "anomalies_detected": 1}


def diagnose_failure_with_ai(repo_id: str, error_logs: str, custom_context: str = ""):
    store = load_store(repo_id) or {}
    tech_stack = store.get("tech_stack", [])
    stack_str = ', '.join([t['name'] if isinstance(t, dict) else str(t) for t in tech_stack])

    messages = [
        {
            "role": "system",
            "content": "You are an expert DevOps engineer and AI Build Doctor. Analyze errors concisely and provide the exact fix."
        },
        {
            "role": "user",
            "content": f"""A deployment failed for a {stack_str} application.

Error Output:
{error_logs[:2000]}

{f"Context: {custom_context}" if custom_context else ""}

Provide:
1. Root cause summary (1-2 sentences)
2. Exact step or command to resolve it
3. Fixed configuration or code snippet if relevant."""
        }
    ]

    diagnosis = call_groq_llm(messages, max_tokens=600)
    return diagnosis
